def set_text(p_el, text):
    runs = p_el.findall(qn('w:r'))
    keep = next((r for r in runs if r.find(qn('w:t')) is not None), runs[0])
    for r in runs:
        if r is not keep:
            p_el.remove(r)
    for h in p_el.findall(qn('w:hyperlink')):
        p_el.remove(h)
    for t in keep.findall(qn('w:t'))[1:]:
        keep.remove(t)
    t = keep.find(qn('w:t'))
    t.text = text
    t.set('{http://www.w3.org/XML/1998/namespace}space', 'preserve')
    for tag in ('w:b', 'w:i'):
        rpr = keep.find(qn('w:rPr'))
        if rpr is not None and rpr.find(qn(tag)) is not None and tmpl_plain.get(id(p_el)):
            rpr.remove(rpr.find(qn(tag)))
    return p_el


